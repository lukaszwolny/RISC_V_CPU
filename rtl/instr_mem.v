/*
Instruction MEM
*/
//-----------------------------------------------------------------------------

module instr_mem #
(
    parameter   depth   =   256
)
(
    // input
    input   [31:0]  i_addr, // address
    // output
    output  [31:0]  o_instr // instruction
);

//===========================================================================
// internal signals
//===========================================================================

reg [31:0]  mem [0:depth-1];    // instr mem 

//===========================================================================
// internal logic
//===========================================================================

// load program
initial begin
    $readmemb("../../mem/program_2.mem",mem);
end

//===========================================================================
// output assignments
//===========================================================================

// instruction output. word 4byte. 
assign o_instr = mem[i_addr[31:2]];

endmodule
